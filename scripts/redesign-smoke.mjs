// Real-cookie UI smoke. Use ONLY an isolated disposable database/API; no production fixtures.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ?? 'playwright-core')
const base = process.env.AUDIT_BASE_URL ?? 'https://localhost:8445'
const password = process.env.AUDIT_ADMIN_PASSWORD
assert.ok(password, 'Supply the isolated development seed password through env')
const output = process.env.AUDIT_OUTPUT ?? '/tmp/trade-redesign-smoke/artifacts'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/usr/bin/chromium', args: ['--no-sandbox'] })
const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 1050 }, timezoneId: 'Europe/Kyiv' })
const page = await context.newPage()
const errors = [], expected = [], warnings = [], checks = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => {
  if (m.type() === 'error') {
    if (m.location().url.includes('/auth/me') && m.text().includes('401')) expected.push('Anonymous /auth/me = 401 before login')
    else errors.push(`${m.text()} ${m.location().url}`)
  }
  if (m.type() === 'warning') warnings.push(m.text())
})
page.on('requestfailed', r => { if (r.failure()?.errorText !== 'net::ERR_ABORTED') errors.push(`${r.url()}: ${r.failure()?.errorText}`) })
async function api(path, data, method = data === undefined ? 'GET' : 'POST') {
  let headers = {}
  if (method !== 'GET') { const csrf = await (await context.request.get(base + '/api/auth/csrf')).json(); headers[csrf.headerName] = csrf.requestToken }
  const response = await context.request.fetch(base + '/api' + path, { method, data, headers })
  assert.ok(response.ok(), `${path}: ${response.status()} ${await response.text()}`)
  return response.status() === 204 ? undefined : response.json()
}
function pass(name) { checks.push(name); console.log('PASS ' + name) }
async function shot(name) {
  await page.screenshot({ path: `${output}/${name}.png`, animations: 'disabled' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page overflow: ${name}`)
}
